"""``python -m switchboard apply``: render the role registry into host-native role files.

    python -m switchboard apply [--write] [--prune] [--home <dir>] [--registry <path>]
                                [--catalog <spawn-sites.json>]

For every registry row it renders two files (decisions R-D7, R-D8 and R-D9):

* ``<home>/.claude/agents/role-<role>.md``: YAML frontmatter ``name``, ``description``,
  ``model`` and ``effort`` (a ``read_only`` row adds ``disallowedTools: Agent, Edit, Write,
  NotebookEdit`` and ``omitClaudeMd: true``), then a one-to-two sentence role prompt.
* ``<home>/.codex/agents/role-<role>.toml``: ``name``, ``description``,
  ``developer_instructions``, ``model`` and ``model_reasoning_effort``. Codex agents cannot
  override permissions, so ``read_only`` is a sentence in ``developer_instructions``.

``inherit`` writes no key, so the host resolves exactly as it does today. Each file starts with
the same provenance comment and nothing run-specific (no time, no registry path), so an
unchanged registry renders byte-identical files. Both emitters are hand-written (stdlib only):
every value is a double-quoted string using only the escapes ``\\\\``, ``\\"`` and
``\\uXXXX``, which mean the same thing in a JSON string, a YAML double-quoted scalar and a TOML
basic string.

Ownership (decision R-D6 and the Step-65 destructive-authority rule). ``--write`` records the
sha256 of every file it writes in ``<home>/.switchboard/generated.json``. A target is updated,
or pruned, only when it has a ledger entry AND its current bytes hash to that entry. Anything
else at a target path is refused and left untouched: a foreign file, a hand edit, a symlink, a
directory, and every existing file when the ledger is missing or unreadable (nothing is then
provably switchboard's). The provenance comment is never consulted for an ownership decision.

Modes. A bare run prints the per-file plan (``create``, ``update``, ``unchanged``, ``refuse``,
plus ``orphan`` for a ledger-owned file whose role left the registry) and writes nothing.
``--write`` acts on the plan: each file is staged in a temp file in the target directory and
renamed into place (a create never replaces a file that appeared after the plan; an update is
re-hashed just before its rename). ``--prune`` turns hash-matching orphans into ``delete`` (and
an orphan entry whose file is already gone into ``forget``); like every other change it happens
only with ``--write``.

Outcomes are returned as data; ``switchboard.cli`` prints them and maps them to exit codes. A
registry that is missing, invalid or cannot be rendered, or a ``--home`` that is not a
directory, raises ``ApplyInputError`` before anything is written (its message is the one
advisory line), so the last-generated files stay as they are. A failed write, delete or ledger
update is returned as an error string; a refusal is a reported plan state, not an error.

Advisories are returned as message strings (cli.py prints each on stderr, prefixed
``switchboard apply: ``) and never change the exit code: a Claude subagent override
environment variable is set; a same-named project agent exists under ``.claude/agents`` in the
current directory or a parent up to its git root (a project agent beats a user agent); and,
with ``--catalog``, a catalog role has no registry row or the catalog is unusable.

HONEST SCOPE: this module writes role definitions. Whether a host dispatch honors them is
proven live by Step R5, not here.
"""

