# --- Generated surface (decisions R-D7, R-D8, R-D9) -----------------------------------------
AGENT_NAME_PREFIX = "role-"
# Home-relative directory of each host's role files. Keys are exactly ``ALLOWED_HOSTS``.
HOST_AGENT_DIRECTORIES: Mapping[str, tuple[str, ...]] = {
    "claude": (".claude", "agents"),
    "codex": (".codex", "agents"),
}
HOST_FILE_SUFFIXES: Mapping[str, str] = {"claude": ".md", "codex": ".toml"}

# The provenance marker. It is a comment in both formats (YAML frontmatter and TOML) and holds
# nothing run-specific, so re-rendering an unchanged registry is byte-identical. It is
# informational only: ownership is decided by the ledger and the current-byte hash.
PROVENANCE_MARKER = "generated by switchboard apply"
PROVENANCE_COMMENT = (
    f"# {PROVENANCE_MARKER} from the committed role registry (switchboard/registry/models.json)."
    " Do not edit: change the registry row and re-run apply; apply never overwrites a hand edit."
)

# ``read_only`` renders Explore-equivalent restrictions.
READ_ONLY_CLAUDE_DISALLOWED_TOOLS: tuple[str, ...] = ("Agent", "Edit", "Write", "NotebookEdit")
READ_ONLY_CODEX_INSTRUCTION = (
    "This role is read-only: do not create, edit, move or delete files (notebooks included) and "
    "do not launch subagents; read, search and report only."
)

# Claude environment variables that defeat or replace a generated per-agent value.
SUBAGENT_OVERRIDE_ENV_VARS: tuple[str, ...] = (
    "CLAUDE_CODE_SUBAGENT_MODEL_FORCE",
    "CLAUDE_CODE_SUBAGENT_MODEL",
    "CLAUDE_CODE_EFFORT_LEVEL",
)
_ENV_VAR_EFFECTS: Mapping[str, str] = {
    "CLAUDE_CODE_SUBAGENT_MODEL_FORCE": "it forces every subagent's model, so the generated "
    "Claude `model` keys are ignored",
    "CLAUDE_CODE_SUBAGENT_MODEL": "it sits below agent frontmatter, so Claude roles whose model "
    "is inherit get that model instead of the session model",
    "CLAUDE_CODE_EFFORT_LEVEL": "it defeats per-agent effort, so the generated Claude `effort` "
    "keys are ignored",
}

# --- Ownership ledger -----------------------------------------------------------------------
LEDGER_SCHEMA_VERSION = 1
LEDGER_FILENAME = "generated.json"
LEDGER_TOP_LEVEL_FIELDS: tuple[str, ...] = ("schema_version", "files")
LEDGER_ENTRY_FIELDS: tuple[str, ...] = ("sha256", "role", "host")
LedgerState = Literal["absent", "ok", "corrupt"]

# --- Spawn-site catalog (skill-mesh ``config/spawn-sites.json``, decision R-D1) -------------
CATALOG_SCHEMA_VERSION = 1

# --- Plan vocabulary ------------------------------------------------------------------------
Action = Literal["create", "update", "unchanged", "refuse", "delete", "orphan", "forget", "error"]
ACTIONS: tuple[Action, ...] = get_args(Action)  # names written once, in the Literal

_SHA256_RE = re.compile(r"[0-9a-f]{64}")
# Escaped as \uXXXX besides C0 controls and DEL: NEL, LS and PS (line breaks to YAML 1.1) and
# the BOM. Registry text is already one line with no C0 control; this is defense in depth.
_EXTRA_ESCAPED: frozenset[int] = frozenset({0x85, 0x2028, 0x2029, 0xFEFF})
# How much of a project agent file is read to find its frontmatter ``name``.
_FRONTMATTER_READ_LIMIT = 16384


class RenderError(ValueError):
    """Raised when a registry value cannot be written as UTF-8 TOML or YAML."""


class LedgerError(ValueError):
    """Raised when the ownership ledger fails validation."""


class ApplyInputError(ValueError):
    """Raised when ``apply`` cannot load or render its inputs; nothing has been written."""


# --- Rendering ------------------------------------------------------------------------------


def agent_name(role: str) -> str:
    """The host-visible agent name for ``role`` (decision R-D7)."""
    return f"{AGENT_NAME_PREFIX}{role}"


def target_key(host: str, role: str) -> str:
    """The home-relative POSIX path of ``role``'s file on ``host``; also its ledger key."""
    return "/".join(
        (*HOST_AGENT_DIRECTORIES[host], f"{agent_name(role)}{HOST_FILE_SUFFIXES[host]}")
    )


def _key_path(home: Path, key: str) -> Path:
    return home.joinpath(*key.split("/"))


def _quote(value: str) -> str:
    """A double-quoted string valid as JSON, a YAML double-quoted scalar and a TOML string."""
    parts = ['"']
    for ch in value:
        code = ord(ch)
        if 0xD800 <= code <= 0xDFFF:
            raise RenderError(f"{value!r} contains a lone surrogate, which UTF-8 cannot encode")
        if ch == "\\":
            parts.append("\\\\")
        elif ch == '"':
            parts.append('\\"')
        elif code < 0x20 or code == 0x7F or code in _EXTRA_ESCAPED:
            parts.append(f"\\u{code:04X}")
        else:
            parts.append(ch)
    parts.append('"')
    return "".join(parts)


def _encode(lines: Sequence[str]) -> bytes:
    text = "\n".join(lines)
    try:
        return text.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise RenderError(f"text cannot be encoded as UTF-8: {exc}") from exc


def role_prompt(row: RoleRow) -> str:
    """The minimal role prompt: one sentence naming the role, then its description."""
    description = row.description.strip()
    if not description.endswith((".", "!", "?")):
        description = f"{description}."
    return f"You are the {row.role} role helper ({agent_name(row.role)}). {description}"


def render_claude(row: RoleRow) -> bytes:
    """``role-<role>.md``: YAML frontmatter, then the role prompt."""
    pin = row.claude
    lines = [
        "---",
        PROVENANCE_COMMENT,
        f"name: {_quote(agent_name(row.role))}",
        f"description: {_quote(row.description)}",
    ]
    if pin.model != INHERIT:
        lines.append(f"model: {_quote(pin.model)}")
    if pin.effort != INHERIT:
        lines.append(f"effort: {_quote(pin.effort)}")
    if row.read_only:
        lines.append(f"disallowedTools: {', '.join(READ_ONLY_CLAUDE_DISALLOWED_TOOLS)}")
        lines.append("omitClaudeMd: true")
    lines.extend(["---", "", role_prompt(row), ""])
    return _encode(lines)


def codex_instructions(row: RoleRow) -> str:
    """``developer_instructions``: the role prompt, plus the read-only sentence when set."""
    prompt = role_prompt(row)
    if row.read_only:
        return f"{prompt} {READ_ONLY_CODEX_INSTRUCTION}"
    return prompt


def render_codex(row: RoleRow) -> bytes:
    """``role-<role>.toml``: a Codex custom-agent definition."""
    pin = row.codex
    lines = [
        PROVENANCE_COMMENT,
        f"name = {_quote(agent_name(row.role))}",
        f"description = {_quote(row.description)}",
        f"developer_instructions = {_quote(codex_instructions(row))}",
    ]
    if pin.model != INHERIT:
        lines.append(f"model = {_quote(pin.model)}")
    if pin.effort != INHERIT:
        lines.append(f"model_reasoning_effort = {_quote(pin.effort)}")
    lines.append("")
    return _encode(lines)


HOST_RENDERERS: Mapping[str, Callable[[RoleRow], bytes]] = {
    "claude": render_claude,
    "codex": render_codex,
}


def render_role_files(rows: Iterable[RoleRow]) -> dict[str, tuple[str, str, bytes]]:
    """Render every row on every host: ``{ledger key: (role, host, bytes)}``.

    Raises ``RenderError`` naming the row when one cannot be rendered; nothing is written then.
    """
    rendered: dict[str, tuple[str, str, bytes]] = {}
    for row in rows:
        for host in ALLOWED_HOSTS:
            try:
                data = HOST_RENDERERS[host](row)
            except RenderError as exc:
                raise RenderError(f"roles[{row.role!r}] on {host}: {exc}") from exc
            rendered[target_key(host, row.role)] = (row.role, host, data)
    return rendered


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --- Ledger model ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class LedgerEntry:
    """One file ``apply --write`` wrote: its sha256 at write time, role and host."""

    sha256: str
    role: str
    host: str

    def to_json(self) -> dict[str, str]:
        return {"sha256": self.sha256, "role": self.role, "host": self.host}


@dataclass(frozen=True, slots=True)
class Ledger:
    """The loaded ledger. Only an ``ok`` ledger's entries grant any update or prune authority."""

    path: Path
    state: LedgerState
    entries: Mapping[str, LedgerEntry]
    error: str | None


def ledger_path(home: Path) -> Path:
    return home / CONFIG_DIRECTORY_NAME / LEDGER_FILENAME


def _is_version(value: object, expected: int) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and value == expected


_reject_duplicate_keys = duplicate_key_rejector(lambda key: LedgerError(f"duplicate key {key!r}"))


def parse_ledger(document: object) -> dict[str, LedgerEntry]:
    """Validate a parsed ledger document. Raises ``LedgerError`` on any defect.

    Every key must be exactly the generated path of its entry's role and host, so a tampered
    ledger can never point ``--prune`` or an update at any other file.
    """
    if not isinstance(document, dict):
        raise LedgerError(f"ledger must be a JSON object, got {type(document).__name__}")
    if set(document) != set(LEDGER_TOP_LEVEL_FIELDS):
        raise LedgerError(
            f"ledger keys must be exactly {list(LEDGER_TOP_LEVEL_FIELDS)}, got {sorted(document)}"
        )
    version = document["schema_version"]
    if not _is_version(version, LEDGER_SCHEMA_VERSION):
        raise LedgerError(f"ledger schema_version must be {LEDGER_SCHEMA_VERSION}, got {version!r}")
    files = document["files"]
    if not isinstance(files, dict):
        raise LedgerError("ledger files must be an object of path -> entry")
    entries: dict[str, LedgerEntry] = {}
    for key, raw in files.items():
        if not isinstance(raw, dict) or set(raw) != set(LEDGER_ENTRY_FIELDS):
            raise LedgerError(
                f"ledger entry {key!r} must have exactly the keys {list(LEDGER_ENTRY_FIELDS)}"
            )
        sha, role, host = raw["sha256"], raw["role"], raw["host"]
        if not isinstance(sha, str) or not _SHA256_RE.fullmatch(sha):
            raise LedgerError(f"ledger entry {key!r} has an invalid sha256")
        if not isinstance(host, str) or host not in HOST_AGENT_DIRECTORIES:
            raise LedgerError(f"ledger entry {key!r} has an unknown host {host!r}")
        if not isinstance(role, str) or not ROLE_NAME_RE.fullmatch(role):
            raise LedgerError(f"ledger entry {key!r} has an invalid role {role!r}")
        if key != target_key(host, role):
            raise LedgerError(
                f"ledger path {key!r} is not the generated path for role {role!r} on {host}"
            )
        entries[key] = LedgerEntry(sha256=sha, role=role, host=host)
    return entries


def load_ledger(home: Path) -> Ledger:
    """Read ``<home>/.switchboard/generated.json``. Never raises.

    A missing file is ``absent``. One that cannot be read, is not JSON, or fails validation is
    ``corrupt``. Either way no entries are returned, so no existing file is provably owned.
    """
    path = ledger_path(home)
    try:
        if not path.exists() and not path.is_symlink():
            return Ledger(path=path, state="absent", entries={}, error=None)
        document = json.loads(
            path.read_bytes().decode("utf-8-sig"), object_pairs_hook=_reject_duplicate_keys
        )
        entries = parse_ledger(document)
    except (OSError, ValueError, RecursionError) as exc:
        # ValueError covers LedgerError, UnicodeDecodeError and json.JSONDecodeError.
        return Ledger(path=path, state="corrupt", entries={}, error=str(exc))
    return Ledger(path=path, state="ok", entries=entries, error=None)


def render_ledger(entries: Mapping[str, LedgerEntry]) -> bytes:
    document = {
        "schema_version": LEDGER_SCHEMA_VERSION,
        "files": {key: entries[key].to_json() for key in sorted(entries)},
    }
    return (json.dumps(document, indent=2, sort_keys=True) + "\n").encode("utf-8")


# --- Planning -------------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class FilePlan:
    """One planned (or, after ``--write``, carried-out) action on one target path."""

    action: Action
    host: str
    role: str
    key: str
    path: Path
    content: bytes | None
    seen_sha256: str | None
    reason: str | None


@dataclass(frozen=True, slots=True)
class _Seen:
    kind: Literal["absent", "file", "other"]
    data: bytes | None
    detail: str | None


def _inspect_target(path: Path) -> _Seen:
    try:
        if path.is_symlink():
            return _Seen(
                kind="other", data=None, detail="it is a symbolic link, not a regular file"
            )
        if not path.exists():
            return _Seen(kind="absent", data=None, detail=None)
        if not path.is_file():
            return _Seen(kind="other", data=None, detail="it is not a regular file")
        return _Seen(kind="file", data=path.read_bytes(), detail=None)
    except OSError as exc:
        return _Seen(kind="other", data=None, detail=f"it could not be read ({exc})")


def _unowned_reason(ledger: Ledger) -> str:
    if ledger.state == "ok":
        return "it has no ledger entry (a foreign or hand-made file); left untouched"
    if ledger.state == "absent":
        return "there is no ledger, so it is not provably switchboard's; left untouched"
    return "the ledger is unreadable, so it is not provably switchboard's; left untouched"


_HAND_EDIT_REASON = (
    "its bytes no longer match the sha256 the ledger recorded (a hand edit); left untouched"
)


def plan_files(
    rendered: Mapping[str, tuple[str, str, bytes]],
    home: Path,
    ledger: Ledger,
    *,
    prune: bool,
) -> list[FilePlan]:
    """Classify every target path and every orphaned ledger entry. Reads only."""
    owned: Mapping[str, LedgerEntry] = ledger.entries if ledger.state == "ok" else {}
    plan: list[FilePlan] = []
    for key, (role, host, content) in rendered.items():
        path = _key_path(home, key)
        base = FilePlan(
            action="create",
            host=host,
            role=role,
            key=key,
            path=path,
            content=content,
            seen_sha256=None,
            reason=None,
        )
        seen = _inspect_target(path)
        if seen.kind == "absent":
            plan.append(base)
            continue
        if seen.kind == "other" or seen.data is None:
            plan.append(replace(base, action="refuse", reason=f"{seen.detail}; left untouched"))
            continue
        sha = sha256_hex(seen.data)
        entry = owned.get(key)
        if entry is None:
            plan.append(replace(base, action="refuse", reason=_unowned_reason(ledger)))
        elif entry.sha256 != sha:
            plan.append(replace(base, action="refuse", reason=_HAND_EDIT_REASON))
        elif seen.data == content:
            plan.append(replace(base, action="unchanged", seen_sha256=sha))
        else:
            plan.append(replace(base, action="update", seen_sha256=sha))

    for key in sorted(owned):
        if key in rendered:
            continue
        entry = owned[key]
        path = _key_path(home, key)
        base = FilePlan(
            action="orphan",
            host=entry.host,
            role=entry.role,
            key=key,
            path=path,
            content=None,
            seen_sha256=None,
            reason=None,
        )
        seen = _inspect_target(path)
        if not prune:
            plan.append(
                replace(
                    base,
                    reason="its role left the registry; --prune --write removes it while its "
                    "bytes still match the ledger",
                )
            )
        elif seen.kind == "absent":
            plan.append(
                replace(base, action="forget", reason="already gone; drops its ledger entry")
            )
        elif seen.kind == "other" or seen.data is None:
            plan.append(replace(base, action="refuse", reason=f"{seen.detail}; not pruned"))
        elif sha256_hex(seen.data) != entry.sha256:
            plan.append(replace(base, action="refuse", reason=_HAND_EDIT_REASON))
        else:
            plan.append(
                replace(
                    base,
                    action="delete",
                    seen_sha256=entry.sha256,
                    reason="its role left the registry",
                )
            )
    return plan


# --- Writing --------------------------------------------------------------------------------


def _discard(path: Path) -> None:
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass


def _stage(directory: Path, name: str, data: bytes) -> Path:
    """Write ``data`` to a fresh temp file in ``directory`` (same filesystem as the target)."""
    fd, tmp_name = tempfile.mkstemp(dir=directory, prefix=f".{name}.", suffix=".tmp")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
    except BaseException:
        _discard(tmp)
        raise
    return tmp


def _install_new(staged: Path, target: Path) -> None:
    """Move ``staged`` to ``target`` without ever replacing an existing ``target``.

    A hard link fails with ``FileExistsError`` when the target exists (POSIX and NTFS). Where
    hard links are unsupported, Windows ``os.rename`` is also no-clobber.
    """
    try:
        os.link(staged, target)
    except FileExistsError:
        raise
    except OSError:
        if os.name != "nt":
            raise
        os.rename(staged, target)


# Run last (after any staging): an edit between this re-hash and the rename/unlink is not caught.
def _still_matches(path: Path, sha: str | None) -> bool:
    seen = _inspect_target(path)
    return seen.kind == "file" and seen.data is not None and sha256_hex(seen.data) == sha


def _apply_one(item: FilePlan, entries: dict[str, LedgerEntry]) -> FilePlan:
    """Carry out one planned action; return its outcome. ``entries`` is updated in place."""
    if item.action in ("create", "update") and item.content is not None:
        item.path.parent.mkdir(parents=True, exist_ok=True)
        staged = _stage(item.path.parent, item.path.name, item.content)
        try:
            if item.action == "create":
                try:
                    _install_new(staged, item.path)
                except FileExistsError:
                    return replace(
                        item, action="refuse", reason="it appeared after the plan; untouched"
                    )
            elif not _still_matches(item.path, item.seen_sha256):
                return replace(item, action="refuse", reason="it changed after the plan; untouched")
            else:
                os.replace(staged, item.path)
        finally:
            _discard(staged)
        entries[item.key] = LedgerEntry(
            sha256=sha256_hex(item.content), role=item.role, host=item.host
        )
        return item
    if item.action == "delete":
        if not _still_matches(item.path, item.seen_sha256):
            return replace(item, action="refuse", reason="it changed after the plan; not pruned")
        item.path.unlink()
        entries.pop(item.key, None)
        return item
    if item.action == "forget":
        entries.pop(item.key, None)
        return item
    return item


def _write_ledger(ledger: Ledger, entries: Mapping[str, LedgerEntry]) -> str | None:
    """Atomically replace the ledger; a corrupt one is first kept beside it. Returns an advisory."""
    advisory: str | None = None
    ledger.path.parent.mkdir(parents=True, exist_ok=True)
    if ledger.state == "corrupt" and (ledger.path.exists() or ledger.path.is_symlink()):
        try:
            digest = sha256_hex(ledger.path.read_bytes())[:16]
        except OSError:
            digest = "unreadable"
        kept = ledger.path.with_name(f"{LEDGER_FILENAME}.corrupt-{digest}")
        os.replace(ledger.path, kept)
        advisory = f"the unreadable ledger was kept as {kept} and a new ledger started"
    staged = _stage(ledger.path.parent, ledger.path.name, render_ledger(entries))
    try:
        os.replace(staged, ledger.path)
    finally:
        _discard(staged)
    return advisory


def execute_plan(
    plan: Sequence[FilePlan], ledger: Ledger
) -> tuple[list[FilePlan], list[str], list[str]]:
    """Carry out ``plan``; return ``(outcomes, errors, advisories)``.

    The ledger is rewritten once at the end (also after a failure, so every file that was
    written is recorded) and only when its entries changed. Hosts may not hot-reload the first
    file in a new directory, so the advisories end with one line per directory this run made.
    """
    new_dirs = sorted(
        {item.path.parent for item in plan if item.action == "create"}
        - {item.path.parent for item in plan if item.path.parent.is_dir()}
    )
    original: dict[str, LedgerEntry] = dict(ledger.entries) if ledger.state == "ok" else {}
    entries = dict(original)
    outcomes: list[FilePlan] = []
    errors: list[str] = []
    advisories: list[str] = []
    try:
        for item in plan:
            try:
                outcomes.append(_apply_one(item, entries))
            except OSError as exc:
                errors.append(f"{item.action} {item.path} failed: {exc}")
                outcomes.append(replace(item, action="error", reason=str(exc)))
    finally:
        if entries != original:
            try:
                note = _write_ledger(ledger, entries)
            except OSError as exc:
                errors.append(
                    f"could not update the ledger {ledger.path}: {exc}; files written in this "
                    "run are not recorded, so later runs refuse them until removed by hand"
                )
            else:
                if note is not None:
                    advisories.append(note)
    advisories.extend(
        f"created {directory}; restart running host sessions so they see it"
        for directory in new_dirs
        if directory.is_dir()
    )
    return outcomes, errors, advisories


