def environment_advisories(environ: Mapping[str, str]) -> list[str]:
    """One line per Claude override variable that is set to a non-empty value."""
    return [
        f"{name}={environ[name]!r} is set; {_ENV_VAR_EFFECTS[name]}"
        for name in SUBAGENT_OVERRIDE_ENV_VARS
        if environ.get(name)
    ]


def _project_agent_directories(start: Path) -> list[Path]:
    """``.claude/agents`` in ``start`` and each parent up to the git root (``start`` only if
    there is no git root)."""
    directories: list[Path] = []
    for directory in (start, *start.parents):
        directories.append(directory / ".claude" / "agents")
        if (directory / ".git").exists():
            return directories
    return [start / ".claude" / "agents"]


def _frontmatter_name(path: Path) -> str | None:
    try:
        with path.open("rb") as fh:
            head = fh.read(_FRONTMATTER_READ_LIMIT)
    except OSError:
        return None
    lines = head.decode("utf-8-sig", errors="replace").splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    for line in lines[1:]:
        if line.strip() == "---":
            return None
        key, sep, value = line.partition(":")
        if sep and key.strip() == "name":
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            return value
    return None


def _same_directory(a: Path, b: Path) -> bool:
    try:
        return a.resolve() == b.resolve()
    except (OSError, RuntimeError):
        return False


def project_agent_advisories(start: Path, home: Path, names: Iterable[str]) -> list[str]:
    """One line per project agent whose file name or frontmatter ``name`` is a role agent name.

    A project ``.claude/agents`` agent beats the user-level one, so it would defeat the pin.
    The user-level directory under ``home`` is never treated as a project directory.
    """
    wanted = set(names)
    user_directory = home.joinpath(*HOST_AGENT_DIRECTORIES["claude"])
    lines: list[str] = []
    for directory in _project_agent_directories(start):
        try:
            if not directory.is_dir() or _same_directory(directory, user_directory):
                continue
            candidates = sorted(directory.rglob("*.md"))
        except OSError:
            continue  # an unreadable directory is skipped: advisories never fail the run
        for path in candidates:
            if not path.is_file():
                continue
            name = path.stem if path.stem in wanted else _frontmatter_name(path)
            if name in wanted:
                lines.append(
                    f"project agent {path} is named {name!r}; in sessions started there it "
                    "overrides the generated user-level role file"
                )
    return lines


def load_catalog(path: str) -> tuple[dict[str, str] | None, str | None]:
    """Read a spawn-site catalog ``{"schema_version": 1, "sites": {site: role|inherit}}``.

    Returns ``(sites, None)`` or ``(None, error)``; never raises. Top-level keys other than
    ``schema_version`` and ``sites`` are ignored so the producer can add metadata.
    """
    try:
        with open(path, encoding="utf-8-sig") as fh:
            document = json.load(fh)
    except (OSError, ValueError, RecursionError) as exc:
        return None, f"could not read it ({exc})"
    if not isinstance(document, dict):
        return None, "it must be a JSON object"
    version = document.get("schema_version")
    if not _is_version(version, CATALOG_SCHEMA_VERSION):
        return None, f"schema_version must be {CATALOG_SCHEMA_VERSION}, got {version!r}"
    sites = document.get("sites")
    if not isinstance(sites, dict):
        return None, "sites must be an object of site id -> role or inherit"
    out: dict[str, str] = {}
    for site, role in sites.items():
        if not isinstance(role, str) or not role:
            return None, f"site {site!r} must map to a role name or {INHERIT!r}, got {role!r}"
        out[site] = role
    return out, None


def catalog_advisories(path: str, roles: Iterable[str]) -> list[str]:
    """One line per catalog role with no registry row, or one line if the catalog is unusable."""
    sites, error = load_catalog(path)
    if sites is None:
        return [f"catalog {path!r} is unusable: {error}; site coverage not checked"]
    known = set(roles)
    missing: dict[str, list[str]] = {}
    for site, role in sites.items():
        if role != INHERIT and role not in known:
            missing.setdefault(role, []).append(site)
    return [
        f"catalog role {role!r} has no registry row (sites: "
        f"{', '.join(repr(site) for site in sorted(missing[role]))}); a dispatch by that role "
        "falls back to the default agent (role_missing)"
        for role in sorted(missing)
    ]


# --- Apply inputs (cli.py prints the run and maps it to an exit code) -----------------------


@dataclass(frozen=True, slots=True)
class ApplyInputs:
    """What one ``apply`` run plans from: the ok registry, its rendered files, home and ledger."""

    registry: RegistryResult
    rendered: Mapping[str, tuple[str, str, bytes]]
    home: Path
    ledger: Ledger


def load_apply_inputs(*, home: str | None, registry_path: str | None) -> ApplyInputs:
    """Load and render the registry, resolve the home and read its ledger. Writes nothing.

    Raises ``ApplyInputError`` when the registry is missing, invalid or cannot be rendered, or
    the home is not a directory.
    """
    registry = load_registry(registry_path)
    if registry.state != "ok":
        raise ApplyInputError(
            f"registry is {registry.state} ({registry.source}): {registry.error}; "
            "nothing written, previously generated files kept"
        )
    try:
        rendered = render_role_files(registry.roles)
    except RenderError as exc:
        raise ApplyInputError(
            f"registry ({registry.source}) cannot be rendered: {exc}; "
            "nothing written, previously generated files kept"
        ) from exc
    home_dir = (Path(home).expanduser() if home is not None else Path.home()).absolute()
    if not home_dir.is_dir():
        raise ApplyInputError(f"home {str(home_dir)!r} is not a directory; nothing written")
    return ApplyInputs(
        registry=registry, rendered=rendered, home=home_dir, ledger=load_ledger(home_dir)
    )


def _current_directory() -> Path | None:
    try:
        return Path.cwd()
    except OSError:
        return None


def preflight_advisories(inputs: ApplyInputs, *, catalog_path: str | None) -> list[str]:
    """The advisories known before planning, in print order. Reads only.

    Override variables, then same-named project agents, then catalog roles with no registry
    row (with ``catalog_path``), then a corrupt ledger.
    """
    role_names = [row.role for row in inputs.registry.roles]
    lines = environment_advisories(os.environ)
    cwd = _current_directory()
    if cwd is not None:
        names = [agent_name(role) for role in role_names]
        lines.extend(project_agent_advisories(cwd, inputs.home, names))
    if catalog_path is not None:
        lines.extend(catalog_advisories(catalog_path, role_names))
    if inputs.ledger.state == "corrupt":
        lines.append(
            f"ledger {inputs.ledger.path} is unreadable ({inputs.ledger.error}); no existing file "
            "is provably switchboard's, so every existing target is refused"
        )
    return lines
